export type Language = keyof typeof translations;
export type TranslationSection = keyof typeof translations.en;
export type TranslationKey<T extends TranslationSection> =
  keyof (typeof translations.en)[T];

export function getTranslation<T extends TranslationSection>(
  language: Language,
  section: T,
  key: TranslationKey<T>
): string {
  const langSection = translations[language]?.[section] as
    | Record<string, string>
    | undefined;
  const enSection = translations.en[section] as Record<string, string>;
  // return (
  //   // (langSection && langSection[key as string]) ?? enSection[key as string]

  // );
  return (
    langSection?.[key as string] ?? enSection?.[key as string] ?? key // fallback to the key name itself
  );
}
